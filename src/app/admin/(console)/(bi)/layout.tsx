import { redirect } from "next/navigation";
import { BusinessSwitcher } from "@/components/bi/business-switcher";
import { JobBanner } from "@/components/bi/job-banner";
import { getBiContext } from "@/server/bi/context";

export const dynamic = "force-dynamic";

/** Business context for the ERP and CRM pages: which business, demo labelling, running jobs. */
export default async function BiLayout({ children }: { children: React.ReactNode }) {
  const resolved = await getBiContext();
  if (!resolved) redirect("/admin/login");
  const tenant = resolved.context?.tenant;
  const job = resolved.context
    ? await resolved.context.db.job.findFirst({ where: { status: { in: ["queued", "running"] } }, orderBy: { createdAt: "desc" }, select: { id: true, progress: true } })
    : null;

  return (
    <main className="min-h-screen w-full px-4 pb-14 pt-8 md:px-8 xl:px-12">
      {tenant?.isDemo && (
        <div role="note" className="mb-4 rounded-xl2 border border-mustard bg-mustard/20 px-4 py-3 text-sm">
          <strong>Demo data.</strong> {tenant.name} is a fictional business generated by code. Its numbers illustrate the product and are not real results.
        </div>
      )}
      <header className="mb-6 flex flex-wrap items-end justify-between gap-4 rounded-2xl border border-mist bg-gradient-to-br from-canvas via-[#eff7f8] to-paper p-5 shadow-panel">
        <div className="min-w-0">
          <p className="text-xs font-semibold uppercase tracking-widest text-graphite">ERP &amp; CRM</p>
          <h1 className="mt-1 font-display text-3xl md:text-4xl">{tenant?.name ?? "Get started"}</h1>
        </div>
        {tenant && (
          <BusinessSwitcher active={tenant.id} options={resolved.memberships.map((m) => ({ tenantId: m.tenantId, name: m.name, isDemo: m.isDemo }))} />
        )}
      </header>
      {job && <JobBanner jobId={job.id} initial={job.progress ?? "Working"} />}
      {children}
    </main>
  );
}
